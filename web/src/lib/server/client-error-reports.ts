import { randomUUID } from 'node:crypto';
import type { RequestEvent } from '@sveltejs/kit';
import { clientErrorReport } from '../client-error-report';
import { RequestLimiter } from './request-security';

const limiter = new RequestLimiter(1000);
const maxBytes = 256;
const rejected = (status: number, retry?: number) => new Response(null, { status,
  headers: retry ? { 'Retry-After': String(retry) } : {} });

export async function receiveClientError(event: Pick<RequestEvent, 'request'|'url'|'getClientAddress'|'locals'>): Promise<Response> {
  if (event.request.headers.get('origin') !== event.url.origin) return rejected(403);
  if (event.url.search || event.request.headers.get('content-type')?.split(';')[0].trim() !== 'application/json') return rejected(400);
  let address = 'unknown';
  try { address = event.getClientAddress(); } catch { /* conservative shared bucket */ }
  const retry = limiter.take('all-client-errors', 100, 60_000)
    || limiter.take(`client-errors:${address}`, 10, 60_000);
  if (retry) return rejected(429, retry);
  const length = event.request.headers.get('content-length');
  if (length && (!/^\d+$/.test(length) || Number(length) > maxBytes)) return rejected(413);
  const reader = event.request.body?.getReader();
  if (!reader) return rejected(400);
  const chunks: Uint8Array[] = [];
  let size = 0;
  let timedOut = false;
  const timeout = setTimeout(() => { timedOut = true; void reader.cancel().catch(() => {}); }, 3000);
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      size += value.byteLength;
      if (size > maxBytes) { void reader.cancel().catch(() => {}); return rejected(413); }
      chunks.push(value);
    }
    if (timedOut) return rejected(408);
    const bytes = new Uint8Array(size);
    let offset = 0;
    for (const chunk of chunks) { bytes.set(chunk, offset); offset += chunk.byteLength; }
    const input: unknown = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes));
    if (!input || typeof input !== 'object' || Array.isArray(input)
      || Object.keys(input).sort().join(',') !== 'errorCode,route,status') return rejected(400);
    const value = input as Record<string, unknown>;
    const metadata = clientErrorReport(value.route, value.errorCode);
    if (!metadata || value.status !== metadata.status) return rejected(400);
    // The only identifier is generated by our request boundary, never supplied
    // by the report. Socket addresses are used transiently for limits only.
    console.error(JSON.stringify({ level: 'error', event: 'browser.failed', ...metadata,
      requestId: event.locals.requestId || randomUUID() }));
    return new Response(null, { status: 204 });
  } catch { return rejected(timedOut ? 408 : 400); }
  finally { clearTimeout(timeout); reader.releaseLock(); }
}
